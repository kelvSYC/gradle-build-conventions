package com.kelvsyc.internal.publishing

import com.kelvsyc.internal.settings.GitHubRepository
import com.kelvsyc.internal.settings.parseGitHubRemote
import com.kelvsyc.internal.settings.readOriginUrl
import org.gradle.api.Action
import org.gradle.api.GradleException
import org.gradle.api.Plugin
import org.gradle.api.Project
import org.gradle.api.Task
import org.gradle.api.provider.Property
import org.gradle.api.provider.ValueSource
import org.gradle.api.provider.ValueSourceParameters
import org.gradle.api.publish.PublishingExtension
import org.gradle.api.publish.maven.MavenPublication
import org.gradle.api.publish.maven.tasks.PublishToMavenRepository
import org.gradle.api.publish.tasks.GenerateModuleMetadata
import java.io.File

/**
 * Project plugin publishing to the GitHub Packages repository of the build's GitHub repository.
 *
 * It applies `maven-publish` and declares the `GitHubPackages` repository at
 * `https://maven.pkg.github.com/<owner>/<name>`, where the repository is named by the `origin`
 * git remote. Without a GitHub `origin`, configuration still succeeds and only publishing to
 * `GitHubPackages` fails.
 *
 * Every Maven publication publishes resolved dependency versions, and the internal platform
 * `com.kelvsyc.internal:platform` is stripped from its POM and Gradle module metadata.
 * [RequireDependencyVersions] then fails module metadata generation, which `check` depends on, if
 * any published dependency is still versionless.
 *
 * GitHub Packages credentials come from the `gpr.user`/`gpr.key` Gradle properties, falling back
 * to the `GITHUB_ACTOR`/`GITHUB_TOKEN` environment variables.
 */
class GitHubPublishingPlugin : Plugin<Project> {
    override fun apply(project: Project) {
        project.pluginManager.apply("maven-publish")

        val rootDir = project.rootDir
        val repository: GitHubRepository? = project.providers.of(OriginUrlValueSource::class.java) {
            parameters.directory.set(rootDir.absolutePath)
        }.orNull?.let(::parseGitHubRemote)

        val user = project.providers.gradleProperty("gpr.user")
            .orElse(project.providers.environmentVariable("GITHUB_ACTOR"))
        val key = project.providers.gradleProperty("gpr.key")
            .orElse(project.providers.environmentVariable("GITHUB_TOKEN"))

        project.extensions.configure(PublishingExtension::class.java) {
            repositories.maven {
                name = REPOSITORY_NAME
                if (repository != null) {
                    setUrl("https://maven.pkg.github.com/${repository.owner}/${repository.name}")
                }
                credentials {
                    username = user.orNull
                    password = key.orNull
                }
            }

            publications.withType(MavenPublication::class.java).configureEach {
                // Publish resolved versions. Dependencies declared without a version (versions from
                // the internal platform, which is stripped below; Kotlin core libraries such as
                // kotlin-reflect; other cores via included builds) would otherwise be published
                // versionless and be unresolvable for consumers.
                // Kotlin Multiplatform target publications (e.g. `js`) are generated by the Kotlin
                // Gradle plugin and do not honour this mapping.
                versionMapping {
                    allVariants {
                        fromResolutionResult()
                    }
                }
                pom.withXml {
                    StripInternalPlatform.fromPom(asNode())
                }
            }
        }

        if (repository == null) {
            // A separate task rather than a doFirst action: it must fail before the publish task's
            // own input validation, which would otherwise report missing credentials instead.
            val requireOrigin = project.tasks.register("requireGitHubOrigin") {
                description = "Fails because the git remote 'origin' does not name a GitHub repository."
                doLast(FailWithoutGitHubOrigin())
            }
            project.tasks.withType(PublishToMavenRepository::class.java).configureEach {
                if (name.endsWith("To${REPOSITORY_NAME}Repository")) {
                    dependsOn(requireOrigin)
                }
            }
        }

        project.tasks.withType(GenerateModuleMetadata::class.java).configureEach {
            doLast(StripInternalPlatform.ModuleMetadataAction())
            doLast(RequireDependencyVersions())
        }

        // Generate module metadata during `check` so RequireDependencyVersions fails in CI, not at
        // release time.
        project.tasks.matching { it.name == "check" }.configureEach {
            dependsOn(project.tasks.withType(GenerateModuleMetadata::class.java))
        }
    }

    private companion object {
        const val REPOSITORY_NAME = "GitHubPackages"
    }
}

/**
 * Fails a publication to `GitHubPackages` when the build has no GitHub `origin` remote to derive
 * the repository URL from.
 */
private class FailWithoutGitHubOrigin : Action<Task> {
    override fun execute(task: Task) {
        throw GradleException(
            "Cannot publish to GitHub Packages: the git remote 'origin' is missing or is not a GitHub " +
                "repository URL, so the GitHubPackages repository URL is unknown. Add an 'origin' remote " +
                "pointing at the GitHub repository to publish to.",
        )
    }
}

/**
 * Reads the `origin` remote URL via [readOriginUrl], so a changed `origin` invalidates the
 * configuration cache.
 */
internal abstract class OriginUrlValueSource : ValueSource<String, OriginUrlValueSource.Params> {
    interface Params : ValueSourceParameters {
        /** Directory from which the git repository is discovered. */
        val directory: Property<String>
    }

    override fun obtain(): String? = readOriginUrl(File(parameters.directory.get()))
}
